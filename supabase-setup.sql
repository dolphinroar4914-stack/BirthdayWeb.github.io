-- Anyone with the friend form can submit a wish. Wishes are public because the
-- birthday jar is public; do not store private information in this table.
create table if not exists public.birthday_wishes (
  id bigint generated by default as identity primary key,
  sender text not null check (char_length(btrim(sender)) between 1 and 28),
  message text not null check (char_length(btrim(message)) between 1 and 160),
  created_at timestamptz not null default now()
);

alter table public.birthday_wishes enable row level security;

grant select, insert on public.birthday_wishes to anon;

drop policy if exists "Anyone can read birthday wishes" on public.birthday_wishes;
create policy "Anyone can read birthday wishes"
  on public.birthday_wishes
  for select
  to anon
  using (true);

drop policy if exists "Anyone can submit birthday wishes" on public.birthday_wishes;
create policy "Anyone can submit birthday wishes"
  on public.birthday_wishes
  for insert
  to anon
  with check (true);
